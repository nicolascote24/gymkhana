// Post-build: writes out/_redirects for Cloudflare, so every page answers at
// one address only. A page is published with a trailing slash (/epreuves-gymkhana/);
// the same address without it gets one direct 301, never a chain.
// Host-level redirects (www -> festivalfalardeau.ca, http -> https) are set in
// the Cloudflare dashboard: see redirect-map.csv.
import { readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = "out";
const lines = ["# Generated by scripts/write-redirects.mjs (npm run build). Do not edit."];

// Renamed pages (redirect-map.csv): the old address goes straight to the new
// one, with or without its trailing slash, in a single 301.
const RENAMED = [["/epreuves", "/epreuves-gymkhana/"]];
for (const [from, to] of RENAMED) lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`);

async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name.startsWith("_") || e.name === "404" || e.name === "images" || e.name === "video" || e.name === "textures") continue;
    const p = path.join(dir, e.name);
    if (await stat(path.join(p, "index.html")).catch(() => null)) {
      const url = "/" + path.relative(OUT, p).split(path.sep).join("/");
      // A renamed address already has its 301 above; a second rule would be dead or a chain.
      if (!RENAMED.some(([from]) => from === url)) lines.push(`${url} ${url}/ 301`);
    }
    await walk(p);
  }
}

await walk(OUT);
await writeFile(path.join(OUT, "_redirects"), lines.join("\n") + "\n");
console.log(`write-redirects: ${lines.length - 1} direct 301 rules (renamed pages, addresses without trailing slash)`);
